import path from "node:path";
import assert from "node:assert/strict";
import { createJiti } from "jiti";
const jiti = createJiti(import.meta.url);
const { bindExerciseCriteria } = await jiti.import(path.resolve("src/lib/pose/exercise-definition.ts"));
const { cameraKneeExtension } = await jiti.import(path.resolve("src/lib/pose/exercises/camera-knee-extension.ts"));
const { poseEngine } = await jiti.import(path.resolve("src/lib/pose/engines/registry.ts"));
const binding = { metricId: 1, checkpointIds: { start: 1, peak: 2, returned: 3 } };
const knee = bindExerciseCriteria(cameraKneeExtension, "left", binding);
// Test-only shoulder definition demonstrates independent joints and thresholds;
// never published to patients or the approved registry.
const shoulder = bindExerciseCriteria({ ...cameraKneeExtension, exerciseCode: "fixture-shoulder", preparationBySide: undefined, landmarksBySide: { left: [13, 11, 23], right: [14, 12, 24] }, start: { min: 10, max: 30 }, returned: { min: 10, max: 30 }, departureMin: 60, correctPeak: { min: 80, max: 100 }, stableMs: 100 }, "right", binding);
assert.deepEqual(shoulder.landmarks, [14, 12, 24]);
const run = (criteria, angles) => { const engine = poseEngine(criteria); const counter = engine.createCounter(criteria); let at = 1000; angles.forEach(angle => { counter.sample(angle, at); at += 200; }); return { engine, counter }; };
const a = run(knee, [90, 90, 125, 165, 90, 90]);
const b = run(shoulder, [20, 20, 65, 90, 20, 20]);
assert.equal(a.counter.repetitions.length, 1); assert.equal(b.counter.repetitions.length, 1);
assert.equal(a.engine.correct(a.counter.repetitions[0], knee), true);
assert.equal(b.engine.correct(b.counter.repetitions[0], shoulder), true);
assert.equal(a.engine.complete(b.counter.repetitions[0], knee), false);
const incorrect = run(shoulder, [20, 20, 65, 70, 20, 20]);
assert.equal(incorrect.counter.repetitions.length, 1);
assert.equal(incorrect.engine.correct(incorrect.counter.repetitions[0], shoulder), false);
b.counter.interrupt(); assert.equal(b.counter.repetitions.length, 1);
a.counter.reset(); assert.equal(a.counter.repetitions.length, 0); assert.equal(b.counter.repetitions.length, 1);
knee.start.min = 1; knee.landmarks[0] = 0; knee.checkpointIds.start = 99;
assert.equal(cameraKneeExtension.start.min, 60); assert.equal(cameraKneeExtension.landmarksBySide.left[0], 23); assert.equal(binding.checkpointIds.start, 1);
assert.throws(() => poseEngine({ ...shoulder, engine: "missing" }));
assert.equal(poseEngine({ ...shoulder, engine: undefined }), poseEngine(shoulder));
console.log("Per-exercise engine isolation: 16 assertions passed.");
